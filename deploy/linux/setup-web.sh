#!/usr/bin/env bash
# One-time setup of the web admin panel: HTTPS via Caddy + Discord login.
# Run as root (sudo) after the bot is installed:   sudo bash setup-web.sh
# Safe to run again (e.g. to change the domain or the Client Secret).
set -euo pipefail

ENV_FILE=/etc/greatnessbot.env
CADDYFILE=/etc/caddy/Caddyfile
SERVICE=greatnessbot
PANEL_PORT=5080

if [ "$(id -u)" -ne 0 ]; then
    echo "Run as root:  sudo bash setup-web.sh"
    exit 1
fi
if [ ! -f "$ENV_FILE" ]; then
    echo "$ENV_FILE not found — install the bot first (install.sh / server-build.sh)."
    exit 1
fi

echo "=== 1/5 Domain ==="
read -rp "Panel domain (e.g. greatness-bot.duckdns.org): " DOMAIN
DOMAIN="${DOMAIN,,}"
DOMAIN="${DOMAIN#https://}"; DOMAIN="${DOMAIN#http://}"; DOMAIN="${DOMAIN%%/*}"
if ! [[ "$DOMAIN" =~ ^[a-z0-9.-]+\.[a-z]{2,}$ ]]; then
    echo "That doesn't look like a domain: '$DOMAIN'"
    exit 1
fi

SERVER_IP="$(curl -4 -s --max-time 5 https://api.ipify.org || true)"
DOMAIN_IP="$(getent ahostsv4 "$DOMAIN" | awk 'NR==1{print $1}' || true)"
echo "Server IP: ${SERVER_IP:-unknown}, $DOMAIN -> ${DOMAIN_IP:-not resolved}"
if [ -n "$SERVER_IP" ] && [ "$SERVER_IP" != "$DOMAIN_IP" ]; then
    echo "WARNING: the domain does not point to this server yet. Set the IP on duckdns.org first,"
    echo "otherwise Caddy can't get an HTTPS certificate."
    read -rp "Continue anyway? [y/N] " yn
    [[ "$yn" =~ ^[Yy]$ ]] || exit 1
fi

echo "=== 2/5 Discord Client Secret ==="
if grep -q '^Web__ClientSecret=' "$ENV_FILE"; then
    read -rp "Client Secret is already set. Replace it? [y/N] " yn
    REPLACE=$([[ "$yn" =~ ^[Yy]$ ]] && echo 1 || echo 0)
else
    REPLACE=1
fi
if [ "$REPLACE" = "1" ]; then
    read -rsp "Paste the Client Secret (Developer Portal -> OAuth2, input is hidden): " SECRET
    echo
    if [ -z "$SECRET" ]; then
        echo "Empty secret. Run setup-web.sh again."
        exit 1
    fi
    sed -i '/^Web__ClientSecret=/d' "$ENV_FILE"
    printf 'Web__ClientSecret=%s\n' "$SECRET" >> "$ENV_FILE"
    chmod 600 "$ENV_FILE"
fi

# Адрес сайта для кнопки «Website» в панелях бота
sed -i '/^Web__PublicUrl=/d' "$ENV_FILE"
printf 'Web__PublicUrl=https://%s\n' "$DOMAIN" >> "$ENV_FILE"

echo "=== 3/5 Caddy (HTTPS reverse proxy) ==="
if ! command -v caddy >/dev/null 2>&1; then
    apt-get update
    apt-get install -y caddy
fi
if [ -f "$CADDYFILE" ] && ! grep -q 'Greatness Bot panel' "$CADDYFILE"; then
    cp "$CADDYFILE" "$CADDYFILE.bak.$(date +%Y%m%d%H%M%S)"
    echo "Old Caddyfile backed up next to it."
fi
cat > "$CADDYFILE" <<EOF
# Greatness Bot panel — generated by setup-web.sh
# Caddy gets and renews the HTTPS certificate (Let's Encrypt) automatically.
$DOMAIN {
    encode gzip
    header {
        Strict-Transport-Security "max-age=31536000"
        -Server
    }
    reverse_proxy 127.0.0.1:$PANEL_PORT
}
EOF
caddy validate --config "$CADDYFILE" --adapter caddyfile
systemctl enable caddy
systemctl restart caddy

echo "=== 4/5 Firewall ==="
if command -v ufw >/dev/null 2>&1 && ufw status | grep -q 'Status: active'; then
    ufw allow 80/tcp
    ufw allow 443/tcp
    echo "ufw: opened 80 and 443"
else
    echo "ufw is not active — nothing to do. If the hosting panel (TENET) has its own firewall, open TCP 80 and 443 there."
fi

echo "=== 5/5 Restart the bot ==="
systemctl restart $SERVICE
sleep 8
if curl -s -o /dev/null --max-time 5 "http://127.0.0.1:$PANEL_PORT/"; then
    echo "Panel answers on 127.0.0.1:$PANEL_PORT"
else
    echo "WARNING: the panel does not answer on 127.0.0.1:$PANEL_PORT — check: journalctl -u $SERVICE -n 50"
fi

echo
echo "Done. Last step in the Discord Developer Portal -> Greatness Bot -> OAuth2 -> Redirects, add:"
echo
echo "    https://$DOMAIN/signin-discord"
echo
echo "Then open https://$DOMAIN and log in with Discord."
echo "Certificate problems: journalctl -u caddy -n 50"
